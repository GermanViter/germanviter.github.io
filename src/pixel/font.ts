export const GLYPH_HEIGHT = 7

export interface Pixel {
  x: number
  y: number
}

export interface PixelLayout {
  width: number
  height: number
  pixels: Pixel[]
}

/**
 * Lay a string out on the pixel grid. Unknown characters fall back to `?`.
 * `tracking` is the gap between glyphs, in pixels.
 */
export function layoutText(text: string, tracking = 1): PixelLayout {
  const pixels: Pixel[] = []
  let cursor = 0

  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char] ?? GLYPHS['?']
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === '#') pixels.push({ x: cursor + x, y })
      }
    })
    cursor += glyph[0].length + tracking
  }

  return { width: Math.max(cursor - tracking, 0), height: GLYPH_HEIGHT, pixels }
}
